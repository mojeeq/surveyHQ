/**
 * Ready-made looks.
 *
 * Dressing a board well from scratch means picking a page ground, a masthead,
 * a canvas, a tab band and a filter bar that all agree, and getting one of the
 * five wrong is what makes a dashboard look worse than the plain grey it
 * started as. These were picked together.
 *
 * Each look is a patch, not a whole appearance: the grid, the logo, the title
 * size and the widget opacity are the board's own and are not touched. Every
 * field stays editable underneath, so a look is a starting point rather than a
 * theme the board is then stuck inside.
 *
 * They are grouped by `family` only for the picker, which is long enough now
 * that a reader scanning it wants the light ones together. A look belongs to
 * exactly one family and nothing else reads the field.
 *
 * Where a look names a `background_pattern`, it is one of the grounds in
 * lib/backgrounds, and its `background_color` is that ground's tint - the two
 * are set together or the ground draws over the wrong colour.
 */
